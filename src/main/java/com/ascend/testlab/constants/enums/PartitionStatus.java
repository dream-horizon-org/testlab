package com.ascend.testlab.constants.enums;

/**
 * Enum representing the partition status.
 *
 * @author Nithya Sree
 * @version 1.0
 * @since 1.0
 */
public enum PartitionStatus {

  /** Indicates the partition is being created. */
  CREATING,

  /** Indicates the partition creation was successful. */
  SUCCESS,

  /** Indicates the partition creation failed. */
  FAILED,

  /** Indicates the partition has been deleted. */
  DELETED
}
